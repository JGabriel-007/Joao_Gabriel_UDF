#include "operacoes.h"

int somar(int num1, int num2) {
    int resultado = num1 + num2;
    return resultado;
}

int subtrair(int num1, int num2) {
    int resultado = num1 - num2;
    return resultado;
}

int multi(int num1, int num2) {
    int resultado = num1 * num2;
    return resultado;
}

int dividir(int num1, int num2) {
    int resultado = num1 / num2;
    return resultado;
}